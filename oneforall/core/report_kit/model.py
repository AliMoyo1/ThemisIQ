"""
A report as data: what the renderers draw.

An adapter (one per report) builds a `Report` from its own figures and hands it to a renderer. Nothing here knows a
module. A chart or a table block carries the very values the page, the CSV and the other formats carry, so the figures
cannot drift between formats, and the tier (board or operational) is an attribute of the report, not of a template.
"""
from dataclasses import dataclass, field
from typing import List, Optional

from core.report_kit import identity, theme


@dataclass
class Actor:
    """Who a report is attributed to. A scheduled or system run names the owner it was run for."""
    name: str
    username: str = ""
    kind: str = "user"            # user | scheduled | system
    owner_name: str = ""
    owner_username: str = ""

    @staticmethod
    def of_user(user) -> "Actor":
        user = user or {}
        return Actor(name=str(user.get("full_name") or user.get("username") or "Unknown user"),
                     username=str(user.get("username") or ""))

    @staticmethod
    def _person(name, username) -> str:
        return f"{name} ({username})" if username and username != name else str(name or "an unnamed owner")

    def describe(self) -> str:
        if self.kind == "user":
            return self._person(self.name, self.username)
        owner = self._person(self.owner_name or self.name, self.owner_username or self.username)
        return f"{'Scheduled run' if self.kind == 'scheduled' else 'System run'} for {owner}"


@dataclass
class Meta:
    title: str
    module: str                       # a module code ("grid") or a navigation name ("Audit")
    tier: str = theme.OPERATIONAL
    subtitle: str = ""
    section: str = ""                 # the page inside the module: "Reports"
    org_name: str = ""
    scope: str = ""
    period: str = ""
    generated_at: object = None       # naive UTC datetime, or its ISO text
    generated_by: Optional[Actor] = None
    exported_by: Optional[Actor] = None
    exported_at: object = None
    reference: str = ""               # "Run 42", "Audit 7"
    confidentiality: str = "Confidential"

    def __post_init__(self):
        if self.tier not in theme.TIERS:
            raise ValueError(f"Unknown report tier: {self.tier}")

    @property
    def module_label(self) -> str:
        return identity.module_name(self.module, self.section or None)

    @property
    def tier_label(self) -> str:
        return theme.TIERS[self.tier]["label"]

    @property
    def tier_chip(self) -> str:
        return theme.TIERS[self.tier]["chip"]

    @property
    def who(self) -> str:
        return self.generated_by.describe() if self.generated_by else "Unknown"

    @property
    def when(self) -> str:
        return identity.format_when(self.generated_at)

    def footer_module(self) -> str:
        return f"Module: {self.module_label}"

    def footer_who(self) -> str:
        return f"Generated by {self.who}"

    def footer_when(self) -> str:
        return f"Generated {self.when}"

    def footer_line(self) -> str:
        """The whole footer text as one line, for formats with a single footer cell (XLSX, DOCX, HTML)."""
        return f"{self.footer_module()}  |  {self.footer_who()}  |  {self.footer_when()}  |  {self.tier_label}"

    def cover_rows(self) -> list:
        """The labelled facts on the cover, in order. Empty ones are left out so the cover never shows a blank."""
        rows = [("Organisation", self.org_name), ("Scope", self.scope), ("Period", self.period),
                ("Module", self.module_label), ("Report type", self.tier_label),
                ("Generated by", self.who), ("Generated", self.when), ("Reference", self.reference)]
        if self.exported_by is not None and self.exported_at:
            rows.append(("Exported by", self.exported_by.describe()))
            rows.append(("Exported", identity.format_when(self.exported_at)))
        return [(label, value) for label, value in rows if value]


